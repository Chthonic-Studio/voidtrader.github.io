// Helper to generate realistic 30-day timeline trend
function generateHistory(basePrice: number, volatility: number, trend: 'up' | 'down' | 'stable') {
  const points = [];
  const now = new Date('2026-11-02T08:00:00Z');
  const days = 30;

  for (let i = days; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const dateStr = d.toISOString().split('T')[0];
    
    let trendFactor = 0;
    if (trend === 'up') trendFactor = (days - i) * 0.012;
    if (trend === 'down') trendFactor = -(days - i) * 0.009;

    const noise = (Math.sin(i * 1.5) * 0.08 + (Math.cos(i * 0.8) * 0.05)) * volatility;
    const avg = Math.max(1, Math.round(basePrice * (1 + trendFactor + noise)));
    const min = Math.max(1, Math.round(avg * 0.9));
    const max = Math.round(avg * 1.15);
    const volume = Math.floor(20 + Math.abs(Math.sin(i)) * 60);

    points.push({
      date: dateStr,
      avg,
      min,
      max,
      volume,
    });
  }
  return points;
}

